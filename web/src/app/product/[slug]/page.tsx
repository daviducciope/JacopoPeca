export async function generateStaticParams() {
  const products = await getStorefrontProducts();

  return products.map((product) => ({
    slug: product.slug,
  }));
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ slug: string }>;
}): Promise<Metadata> {
  const { slug } = await params;
  const product = await getStorefrontProductBySlug(slug);
  if (!product) return { title: "Prodotto non trovato", robots: { index: false, follow: true } };
  const image =
    product.images.find((item) => item.isThumbnail) || product.images[0];
  const title = productSeoTitle(product);
  const description = productSeoDescription(product);
  const categoryKeywords = getCategorySeo(product.categorySlug)?.keywords ?? [];

  return {
    title: { absolute: title },
    description,
    keywords: [
      product.name,
      product.categoryName,
      productSeoLabel(product),
      "Jacopo Peca",
      ...categoryKeywords,
    ],
    alternates: {
      canonical: `/product/${product.slug}`,
    },
    openGraph: {
      type: "website",
      title,
      description,
      url: `/product/${product.slug}`,
      images: image
        ? [{ url: absoluteUrl(image.url), alt: buildProductImageAlt(product, image.alt) }]
        : undefined,
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
      images: image ? [absoluteUrl(image.url)] : undefined,
    },
  };
}

function isAutoGeneratedDescription(product: AppProduct) {
  const trimmed = (product.description || "").trim();
  if (!trimmed) return true;
  const defaultPattern = `${product.name} - ${product.categoryName} handmade Jacopo Peca.`;
  return trimmed.toLowerCase() === defaultPattern.toLowerCase();
}

